"""Closed-loop brief for the LLM pod (RD-Agent / Alpha-GPT style): what was tried, what worked, what failed and why.

Usage: python tools/feedback.py   -> knowledge/feedback-brief.md (the Scout/Writer MUST read it before proposing)
Built from alphas/registry.csv, the drafts' code (legs via tools/diversity.py) and knowledge/variables.json.
"""
import csv
import json
import re
from pathlib import Path

from diversity import legs, KNOWN, SAT
from allocate import source

ROOT = Path(__file__).resolve().parent.parent


def main():
    reg = list(csv.DictReader((ROOT / "alphas" / "registry.csv").open(encoding="utf-8")))
    exprs = {}
    for f in (ROOT / "alphas" / "drafts").glob("*.json"):
        for it in json.loads(f.read_text(encoding="utf-8")):
            exprs.setdefault(it["tag"], it["expr"])
    ran = [r for r in reg if r["slow_ir"]]
    subs = [r for r in reg if r["status"] == "SUBMITTED"]
    use = {}
    for r in subs:
        for l in KNOWN.get(r["tag"]) or legs(exprs.get(r["tag"], "")):
            use[l] = use.get(l, 0) + 1
    sat = sorted(l for l, n in use.items() if n >= SAT)
    by = {}
    for r in ran:
        s = source(r["tag"])
        b = by.setdefault(s, [0, 0, 0, -9])
        ir = float(r["slow_ir"])
        b[0] += 1
        b[1] += ir >= .065
        b[2] += r["status"] == "SUBMITTED"
        b[3] = max(b[3], ir)
    near = sorted((r for r in ran if r["status"] != "SUBMITTED" and float(r["slow_ir"]) >= .06),
                  key=lambda r: -float(r["slow_ir"]))[:12]
    weak_free = sorted((r for r in ran if abs(float(r["slow_ir"])) >= .02 and r["slow_corr"] and float(r["slow_corr"]) <= .5
                        and r["oos1"] and float(r["oos1"]) * float(r["slow_ir"]) > 0), key=lambda r: -abs(float(r["slow_ir"])))[:15]
    used_vars = set()
    for r in ran:
        used_vars |= set(re.findall(r"[a-z_][a-z0-9_]+", "\n".join(l.split("#")[0] for l in exprs.get(r["tag"], "").splitlines())))
    allv = json.loads((ROOT / "knowledge" / "variables.json").read_text())
    unused = [v for v in allv if v not in used_vars and not re.match(r"^(days_|day_of|month_of|quarter_of|cpi_|gdp|real_gdp|unemployment|trading_days)", v)]
    L = ["# Feedback brief for the LLM pod (generated by tools/feedback.py; read before proposing anything)", "",
         f"Slow runs: {len(ran)}. Submitted: {len(subs)}. Rule: the portal needs IR > .07 and corr <= .5 to every pool alpha, "
         "or IR/sqrt(TVR) >= 1.2x the blocker's. Our own diversity rule bans saturated legs.", "",
         f"## Saturated legs (used in >= {SAT} submissions; do NOT build on them)", ", ".join(sat) or "none", "",
         "## Yield by source (Slow runs / IR >= .065 / submitted / best IR)"]
    L += [f"- {s}: {b[0]} / {b[1]} / {b[2]} / {b[3]:.3f}" for s, b in sorted(by.items(), key=lambda x: -x[1][2])]
    L += ["", "## Near-misses (IR >= .06, not submitted): what blocked them"]
    L += [f"- {r['tag']}: IR {r['slow_ir']}, TVR {r['slow_tvr']}, corr {r['slow_corr']} to {r['blocker']} (bar {r['bar_irtvr']}), OOS1 {r['oos1']}" for r in near]
    L += ["", "## Weak but usable legs (|IR| >= .02, pool corr <= .5, same sign out of sample): composite ingredients"]
    L += [f"- {r['tag']}: IR {r['slow_ir']}, corr {r['slow_corr']}, OOS1 {r['oos1']}" for r in weak_free]
    L += ["", "## Dead ends (do not repeat)",
          "- Textbook anomalies at daily IR: 52-week high, BAB, value x quality, earnings drift, MAX, high-volume premium, tug of war, realised skew, VIX beta, plain/residual/volume momentum, FROG.",
          "- Single-field sweep alphas alone (0 of 88 above IR .05); calendar seasonality (N_TOMSEAS/N_OPEXSEAS ~0); gold beta, last-hour volume share ~0.",
          "- On/off regime gates (turnover explodes); 0/1 banding flags; more slow weight on a blend whose blocker shares that slow leg.",
          "", f"## Data never used in any simulated alpha ({len(unused)} fields)", ", ".join(unused[:120])]
    (ROOT / "knowledge" / "feedback-brief.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"feedback brief: {len(ran)} runs, {len(near)} near-misses, {len(weak_free)} usable legs, {len(unused)} unused fields")


if __name__ == "__main__":
    main()

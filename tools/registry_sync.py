"""Rebuild alphas/registry.csv and alphas/registry.md from every runner snapshot (CLAUDE.md record-keeping rule).

Usage: python tools/registry_sync.py
Existing rows are kept; a tag seen in any snapshot (newest wins) is added or updated. Tags queued for the runner
(alphas/queue/ops.json front, alphas/queue/next.json) without a result yet are added as QUEUED.
expr_file = the alphas/drafts/*.json file holding the tag's expression, if any.
"""
import csv
import glob
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "alphas" / "registry.csv"
MD = ROOT / "alphas" / "registry.md"
F = ("tag|state|lb|wlb|f_ir|f_tvr|f_irtvr|f_corr|f_elig|f_rw|f_best|s_ir|s_tvr|s_irtvr|s_corr|s_corrId|"
     "s_corrIrTvr|s_corrOwn|s_elig|s_oos1|s_rw|s_best|s_vt|err").split("|")


def num(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def status(r):
    st = r["state"]
    if st == "submitted":
        return "SUBMITTED"
    if st in ("skipped",):
        return "SKIPPED"
    if st in ("ffail", "sfail", "ftimeout", "stimeout", "subfail"):
        return "FAILED"
    if st in ("queued", "squeued"):
        return "QUEUED"
    if st in ("fsim", "ssim", "subq"):
        return "RUNNING"
    if st == "fdone":
        return "FAST ONLY (not Slow-tested)"
    ir, tvr = num(r["s_ir"]), num(r["s_tvr"])
    if ir == 0 and tvr == 0:
        return "EMPTY"
    if r.get("s_elig") == "1":
        return "ELIGIBLE (not submitted)"
    if ir is not None and ir < 0.07:
        return "REJECTED: IR"
    return "REJECTED: correlation"


def main():
    rows, order = {}, []
    if CSV.exists():
        with CSV.open(encoding="utf-8") as f:
            rd = csv.DictReader(f)
            cols = rd.fieldnames
            for r in rd:
                rows[r["tag"]] = r
                order.append(r["tag"])
    exprs, fams = {}, {}
    for f in sorted((ROOT / "alphas" / "drafts").glob("*.json")):
        for it in json.loads(f.read_text(encoding="utf-8")):
            exprs.setdefault(it["tag"], f"alphas/drafts/{f.name}")
            fams.setdefault(it["tag"], it.get("family") or it.get("base") or "")
    snap = {}
    for f in sorted(glob.glob(str(ROOT / "alphas" / "snapshots" / "2*.txt"))):
        if "px" in f:
            continue
        for line in open(f, encoding="utf-8"):
            c = line.rstrip("\n").split("|")
            if len(c) >= len(F) - 1 and c[0] and not c[0].startswith("ELIGIBLE"):
                snap[c[0]] = dict(zip(F, c + [""] * (len(F) - len(c))))
                snap[c[0]]["_batch"] = Path(f).stem
    for tag, r in snap.items():
        old = rows.get(tag, {})
        new = dict(old)
        new.update({
            "tag": tag, "family": old.get("family") or fams.get(tag, tag.split("_")[0]),
            "batch": old.get("batch") or f"snapshot {r['_batch']}", "status": status(r),
            "slow_ir": r["s_ir"], "slow_tvr": r["s_tvr"], "slow_irtvr": r["s_irtvr"], "slow_corr": r["s_corr"],
            "blocker": ("#" + r["s_corrId"]) if r["s_corrId"] else "", "bar_irtvr": r["s_corrIrTvr"],
            "oos1": r["s_oos1"], "recency_ir": r["s_rw"], "best_year": r["s_best"],
            "fast_ir": r["f_ir"] or old.get("fast_ir", ""), "fast_corr": r["f_corr"] or old.get("fast_corr", ""),
            "lookback": r["lb"] or old.get("lookback", ""),
            "expr_file": exprs.get(tag) or old.get("expr_file") or "runner R3_jobs (not in repo)",
        })
        if tag not in rows:
            order.append(tag)
        rows[tag] = new
    queued = []
    ops = ROOT / "alphas" / "queue" / "ops.json"
    if ops.exists():
        queued += json.loads(ops.read_text()).get("front", [])
    nxt = ROOT / "alphas" / "queue" / "next.json"
    if nxt.exists():
        queued += [j["tag"] for j in json.loads(nxt.read_text())]
    for tag in queued:
        if tag not in rows:
            rows[tag] = {"tag": tag, "family": fams.get(tag, ""), "batch": "queued", "status": "QUEUED",
                         "expr_file": exprs.get(tag, "")}
            order.append(tag)
    with CSV.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for t in order:
            w.writerow({k: rows[t].get(k, "") for k in cols})
    counts = {}
    for t in order:
        s = rows[t].get("status", "").split(" (")[0]
        counts[s] = counts.get(s, 0) + 1
    md = ["# Alpha registry (every alpha ever simulated or queued; generated by tools/registry_sync.py)", "",
          "Counts: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())), "",
          "| Tag | Family | Status | Slow IR | TVR | IR/sqrtTVR | Corr | Blocker | Bar | Expr file |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for t in order:
        r = rows[t]
        md.append("| " + " | ".join(str(r.get(k, "")) for k in ("tag", "family", "status", "slow_ir", "slow_tvr",
                                                                   "slow_irtvr", "slow_corr", "blocker",
                                                                   "bar_irtvr", "expr_file")) + " |")
    MD.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"registry: {len(order)} alphas; " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))


if __name__ == "__main__":
    main()

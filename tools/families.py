"""Per-family scoreboard from alphas/ledger.md -> reports/families.md.

Used each cycle to pick under-tested families and to cap drafts at 5 per family.
Usage: python tools/families.py
"""
import json
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEDGER = ROOT / "alphas" / "ledger.md"
OUT = ROOT / "reports" / "families.md"


def f(x):
    try:
        return float(x)
    except ValueError:
        return None


def main():
    fam = defaultdict(list)
    tested = set()
    for l in LEDGER.read_text(encoding="utf-8").splitlines():
        c = [x.strip() for x in l.strip().strip("|").split("|")]
        if len(c) != 13 or c[1] in {"Tag", "---"}:
            continue
        tested.add(c[1])
        fam[c[2]].append({"ir": f(c[3]), "corr": f(c[6]), "fe": c[7] == "yes", "sir": f(c[8]),
                          "se": c[10] == "yes", "sub": c[12] == "yes"})
    pending = defaultdict(int)
    for p in (ROOT / "alphas" / "drafts").glob("*.json"):
        for it in json.loads(p.read_text(encoding="utf-8")):
            if it["tag"] not in tested:
                pending[it.get("family") or it.get("base", "?")] += 1

    rows = []
    for name in sorted(set(fam) | set(pending)):
        xs = fam.get(name, [])
        irs = [x["ir"] for x in xs if x["ir"] is not None]
        cs = [x["corr"] for x in xs if x["corr"] is not None]
        rows.append([name, len(irs), pending.get(name, 0),
                     f"{max(irs):.3f}" if irs else "", f"{statistics.median(cs):.2f}" if cs else "",
                     sum(x["fe"] for x in xs), sum(x["sir"] is not None for x in xs),
                     sum(x["se"] for x in xs), sum(x["sub"] for x in xs)])
    rows.sort(key=lambda r: (-(float(r[3]) if r[3] else 0)))
    head = ["Family", "Fast tested", "Drafts pending", "Best F IR", "Median F corr", "F eligible",
            "Slow tested", "S eligible", "Submitted"]
    md = ["# Family scoreboard (generated by tools/families.py)", "",
          "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    md += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    OUT.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md[2:]))


if __name__ == "__main__":
    main()
